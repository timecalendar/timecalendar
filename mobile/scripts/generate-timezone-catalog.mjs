import { createRequire } from "node:module"
import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

import { rawTimeZones, timeZonesNames } from "@vvo/tzdb"

const require = createRequire(import.meta.url)
const root = fileURLToPath(new URL("..", import.meta.url))
const outputPath = fileURLToPath(
  new URL("../src/features/settings/data/timezone-catalog.generated.ts", import.meta.url),
)
const locales = ["en", "fr"]

const packageVersion = (name) => require(`${name}/package.json`).version

function cldr(locale, packageName, file, path) {
  let value = require(`${packageName}/main/${locale}/${file}.json`)
  for (const part of path) value = value?.[part]
  return value
}

function exemplar(locale, identifier) {
  return cldr(locale, "cldr-dates-full", "timeZoneNames", [
    "main",
    locale,
    "dates",
    "timeZoneNames",
    "zone",
    ...identifier.split("/"),
    "exemplarCity",
  ])
}

function territory(locale, countryCode) {
  if (!countryCode) return undefined
  return cldr(locale, "cldr-localenames-full", "territories", [
    "main",
    locale,
    "localeDisplayNames",
    "territories",
    countryCode,
  ])
}

const metadataByIdentifier = new Map()
for (const zone of rawTimeZones) {
  for (const identifier of new Set([zone.name, ...zone.group])) {
    if (!metadataByIdentifier.has(identifier)) metadataByIdentifier.set(identifier, zone)
  }
}

const identifiers = [...new Set([
  ...timeZonesNames,
  ...rawTimeZones.flatMap((zone) => [zone.name, ...zone.group]),
  "UTC",
])].sort()

const records = identifiers.map((id) => {
  const metadata = metadataByIdentifier.get(id)
  const labels = Object.fromEntries(
    locales.map((locale) => [
      locale,
      {
        exemplarCity: exemplar(locale, id),
        territory: territory(locale, metadata?.countryCode),
      },
    ]),
  )
  return {
    id,
    alternativeName: metadata?.alternativeName,
    countryCode: metadata?.countryCode,
    countryName: metadata?.countryName,
    mainCities: metadata?.mainCities ?? [],
    labels,
  }
})

const provenance = {
  "@vvo/tzdb": packageVersion("@vvo/tzdb"),
  "cldr-dates-full": packageVersion("cldr-dates-full"),
  "cldr-localenames-full": packageVersion("cldr-localenames-full"),
}

const content = `// Generated by scripts/generate-timezone-catalog.mjs. Do not edit.\n` +
  `// Inputs: ${Object.entries(provenance).map(([name, version]) => `${name}@${version}`).join(", ")}\n` +
  `export const TIMEZONE_CATALOG_PROVENANCE = ${JSON.stringify(provenance, null, 2)} as const\n\n` +
  `export const GENERATED_TIMEZONE_CATALOG = ${JSON.stringify(records, null, 2)} as const\n`

if (process.argv.includes("--check")) {
  const existing = await readFile(outputPath, "utf8").catch(() => "")
  if (existing !== content) {
    console.error("Generated timezone catalog is stale. Run npm run generate:timezone-catalog.")
    process.exitCode = 1
  }
} else {
  await writeFile(outputPath, content)
}
